"""Minimal locale strings (English / Russian)."""

from __future__ import annotations

import locale
import os

_LANG = "en"


def init(lang: str | None = None) -> str:
    global _LANG
    if lang:
        _LANG = "ru" if lang.lower().startswith("ru") else "en"
        return _LANG
    env = (
        os.environ.get("LC_ALL")
        or os.environ.get("LC_MESSAGES")
        or os.environ.get("LANG")
        or ""
    )
    try:
        loc = locale.getlocale()[0] or ""
    except Exception:
        loc = ""
    blob = f"{env} {loc}".lower()
    _LANG = "ru" if "ru" in blob else "en"
    return _LANG


def lang() -> str:
    return _LANG


def t(key: str, **kwargs) -> str:
    table = RU if _LANG == "ru" else EN
    text = table.get(key) or EN.get(key) or key
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text


